"""
MKMSG.PY - check DIALDOS.MSG and regenerate the message-number header DIALDOS.H.

DS-DOS Shell for The Major BBS v10
Copyright (C) 1996-2026 DialSoft Corp.

DIALDOS.MSG is the hand-maintained source of the module's text.  It holds
raw control bytes (ESC for ANSI color, CP437 box-drawing characters), so this
script reads and writes it as bytes and never re-encodes it.

What it does:
  1. Normalizes DIALDOS.MSG to CRLF line endings.  The Major BBS
     configuration editor cannot read a file with bare LF line endings.
  2. Writes DIALDOS.H, numbering the entries the way the BBS's message
     compiler does: the first LEVELn marker takes no slot; every later
     named entry, including each later LEVELn marker, takes the next slot.
     LEVELn markers get no #define.
  3. Refuses names longer than 8 characters, duplicate names and a second
     marker for the same LEVEL (the configuration editor shows only the
     first one).

Usage:  python TOOLS/MKMSG.PY   (run from the project root)
"""

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRCDIR = os.path.join(ROOT, "SRC", "DIALDOS")
MSGFILE = os.path.join(SRCDIR, "DIALDOS.MSG")
HDRFILE = os.path.join(SRCDIR, "DIALDOS.H")

MOPTLEN = 8          # longest allowed message name


def fail(text):
    sys.exit("MKMSG: " + text)


def scan(text):
    """Return the entry names in file order.

    The name of an entry is the last run of letters/digits before its '{'.
    The body runs to the next '}' that is not escaped with '~'.
    """
    names, i, n = [], 0, len(text)
    while True:
        j = text.find("{", i)
        if j < 0:
            break
        m = re.search(r"([A-Za-z0-9]+)[^A-Za-z0-9]*$", text[i:j])
        if not m:
            fail("an entry with no name before '{' at offset %d" % j)
        k, esc = j + 1, False
        while k < n:
            c = text[k]
            if esc:
                esc = False
            elif c == "~":
                esc = True
            elif c == "}":
                break
            k += 1
        if k >= n:
            fail("no closing '}' for " + m.group(1))
        names.append(m.group(1))
        i = k + 1
    return names


def is_level(name):
    return name.startswith("LEVEL") and name[5:].isdigit()


def main():
    # Optional arguments let the numbering be checked against another file
    # without touching it: MKMSG.PY <msgfile> <hdrfile>
    msgfile = sys.argv[1] if len(sys.argv) > 1 else MSGFILE
    hdrfile = sys.argv[2] if len(sys.argv) > 2 else HDRFILE
    with open(msgfile, "rb") as f:
        raw = f.read()
    raw = raw.replace(b"\r\n", b"\n")
    names = scan(raw.decode("latin-1"))

    seen, levels = set(), set()
    for name in names:
        if len(name) > MOPTLEN:
            fail("message name longer than %d characters: %s" % (MOPTLEN, name))
        if name in seen:
            fail("duplicate message name: " + name)
        seen.add(name)
        if is_level(name):
            if name in levels:
                fail(name + " appears twice; the CNF editor shows only the first")
            levels.add(name)
    if not names or not is_level(names[0]):
        fail("the file must start with a LEVELn marker")

    if msgfile == MSGFILE:
        with open(msgfile, "wb") as f:
            f.write(raw.replace(b"\n", b"\r\n"))

    # The first LEVELn marker takes no slot; numbering starts at 1 with the
    # entry after it.
    lines = ['/*  Message-number definitions derived from "DIALDOS.MSG"  */',
             '/*  Generated by TOOLS/MKMSG.PY - do not edit by hand.      */', ""]
    for slot, name in enumerate(names[1:], start=1):
        if not is_level(name):
            lines.append("#define %-9s %3d" % (name, slot))
    with open(hdrfile, "w", newline="\r\n") as f:
        f.write("\n".join(lines) + "\n")

    print("MKMSG: %d entries -> %s" % (len(names), hdrfile))


if __name__ == "__main__":
    main()
